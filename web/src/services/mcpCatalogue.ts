export function mcpToolSummary(tool: MCPTool) { return coreDescriptions[tool.name] || tool.description.split(/[。；]/)[0]; }

export function mcpToolCategory(tool: MCPTool): MCPCategory {
  // Prefer the most specific prefix (credential.operation before credential).
  let match: MCPCategory = mcpCategories[mcpCategories.length - 1], length = 0;
  for (const category of mcpCategories) for (const root of category.roots) {
    if ((tool.capability === root || tool.capability.startsWith(`${root}.`)) && root.length > length) {
      match = category; length = root.length;
    }
  }
  return match;
}

export function mcpToolTitle(tool: MCPTool) { return mcpToolTitles[tool.name] || tool.name; }
export function mcpToolMatches(tool: MCPTool, query: string) {
  const text = `${mcpToolTitle(tool)} ${mcpToolSummary(tool)} ${tool.name} ${tool.description} ${tool.capability} ${mcpToolCategory(tool).label}`.toLocaleLowerCase();
  return query.trim().toLocaleLowerCase().split(/\s+/).every(word => text.includes(word));
}
